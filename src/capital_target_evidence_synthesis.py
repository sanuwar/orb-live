"""M54 (Issue #360): $30K capital-target evidence synthesis and
forward-path decision gate.

M54 is NOT a new strategy experiment. This module holds ONLY the
mechanical, pure arithmetic used to interpret already-committed
M43-M53 results: the percent-return implied by a fixed dollar target
on a given starting capital, its simple and compounded annualizations,
the linear-scaling capital estimate needed to reach a target from an
already-observed historical mean, and the dollar drawdown implied at
that scaled capital holding the observed drawdown PERCENTAGE fixed.

No new backtest, no new market data, no strategy alteration -- every
number these functions consume is drawn from an already-committed
M43-M53 report or result artifact; this module never fetches or
computes a fresh strategy result. The consolidated evidence tables
themselves (milestone-by-milestone figures, classifications, data
limitations) are curated directly in
`docs/research/CAPITAL_TARGET_EVIDENCE_SYNTHESIS_M54.md`, not
generated by code -- they are a narrative reconciliation of existing
documents, not a new computation, so they do not belong in this
module. What DOES belong here is the arithmetic applied to those
curated figures, since that arithmetic is genuinely error-prone by
hand and benefits from dedicated, deterministic tests.
"""
from __future__ import annotations

from decimal import Decimal

__all__ = [
    "STARTING_CAPITAL_30K",
    "TARGET_MONTHLY_500",
    "TARGET_MONTHLY_1000",
    "CapitalTargetEvidenceError",
    "monthly_return_pct_for_target",
    "simple_annual_pct",
    "compounded_annual_pct",
    "required_capital_for_target",
    "scaled_drawdown_dollars",
]

#: The fixed starting capital every M43-M53 $30K-account design used.
STARTING_CAPITAL_30K = Decimal("30000")

#: The two frozen dollar targets Issue #360 asks about. No other target
#: is in scope for M54 -- these are not swept or tuned.
TARGET_MONTHLY_500 = Decimal("500")
TARGET_MONTHLY_1000 = Decimal("1000")


class CapitalTargetEvidenceError(RuntimeError):
    """Refused: an M54 (Issue #360) capital-scaling precondition failed
    -- e.g. an attempt to scale a non-positive observed monthly profit
    to a target, or a non-positive capital base. Never silently
    substituted or guessed."""


def monthly_return_pct_for_target(*, target_monthly_dollars: Decimal, capital: Decimal = STARTING_CAPITAL_30K) -> Decimal:
    """The monthly percent return a fixed dollar target implies on
    `capital`: `target_monthly_dollars / capital`. E.g. $500/month on
    $30,000 = 1.6667%."""
    if capital <= 0:
        raise CapitalTargetEvidenceError(f"capital must be positive, got {capital}")
    return target_monthly_dollars / capital


def simple_annual_pct(monthly_pct: Decimal) -> Decimal:
    """Simple (non-compounding) annualization: `monthly_pct * 12`. E.g.
    1.6667%/month simple-annualizes to 20%."""
    return monthly_pct * 12


def compounded_annual_pct(monthly_pct: Decimal) -> Decimal:
    """Compounded annualization: `(1 + monthly_pct)^12 - 1`. Reported
    alongside the simple figure per Issue #360's explicit requirement
    -- the two are not interchangeable and both are always reported
    together, never one substituted for the other."""
    return (1 + monthly_pct) ** 12 - 1


def required_capital_for_target(
    *, target_monthly_dollars: Decimal, observed_mean_monthly_dollars: Decimal,
    observed_starting_capital: Decimal = STARTING_CAPITAL_30K,
) -> Decimal:
    """Linear-scaling capital estimate, Issue #360's exact frozen
    formula: `observed_starting_capital * target_monthly_dollars /
    observed_mean_monthly_dollars`. This is a mechanical rescaling of
    an ALREADY-OBSERVED historical mean -- never a forecast or a
    guarantee, and it assumes the historical percent return holds
    unchanged at the larger capital (an assumption stated explicitly
    wherever this function's result is reported, not implied
    silently). Refuses (raises) on a non-positive observed mean:
    scaling a loss or breakeven result to "reach" a positive dollar
    target is not a meaningful calculation, so it is never attempted."""
    if observed_starting_capital <= 0:
        raise CapitalTargetEvidenceError(f"observed_starting_capital must be positive, got {observed_starting_capital}")
    if observed_mean_monthly_dollars <= 0:
        raise CapitalTargetEvidenceError(
            f"cannot scale a non-positive observed mean monthly profit ({observed_mean_monthly_dollars}) to a target -- refusing to guess"
        )
    return observed_starting_capital * target_monthly_dollars / observed_mean_monthly_dollars


def scaled_drawdown_dollars(*, required_capital: Decimal, observed_max_drawdown_pct: Decimal) -> Decimal:
    """Dollar drawdown implied at the linearly-scaled `required_capital`,
    holding the OBSERVED drawdown PERCENTAGE fixed:
    `required_capital * observed_max_drawdown_pct`. This explicitly
    does NOT assume drawdown percentage improves with more capital --
    it assumes the same percentage risk profile scales proportionally,
    the most conservative default absent contrary evidence, and it is
    always reported next to a stated non-guarantee warning."""
    if required_capital < 0:
        raise CapitalTargetEvidenceError(f"required_capital must be non-negative, got {required_capital}")
    if observed_max_drawdown_pct < 0:
        raise CapitalTargetEvidenceError(f"observed_max_drawdown_pct must be non-negative, got {observed_max_drawdown_pct}")
    return required_capital * observed_max_drawdown_pct
